export default {
  id: 'mbti',
  name: '16 型人格测试',
  short: '16型人格',
  icon: 'puzzle',
  tint: '#5856d6',
  category: 'personality',
  minutes: 6,
  shareable: true,
  intro: '基于荣格心理类型理论的四个偏好维度：精力来源（E/I）、信息获取（S/N）、决策方式（T/F）与生活态度（J/P）。共 32 题，根据第一直觉作答即可。',
  prompt: '你在多大程度上同意这句话？',
  scale: AGREE5,
  scaleStyle: 'agree',
  reference: '题目为原创，理论依据：C. G. Jung《心理类型》；Myers & Briggs 类型理论。本测试并非官方 MBTI® 测评。',
  items,
  score(answers) {
    const sums = {};
    const counts = {};
    items.forEach((it, i) => {
      const dim = DIMS.find((d) => d.k === it.k);
      const sign = it.p === dim.a ? 1 : -1;
      sums[it.k] = (sums[it.k] || 0) + (answers[i] - 3) * sign;
      counts[it.k] = (counts[it.k] || 0) + 1;
    });
    const rows = DIMS.map((d) => {
      const pa = clamp(round(50 + (50 * sums[d.k]) / (2 * counts[d.k])));
      return { ...d, pa, letter: pa >= 50 ? d.a : d.b };
    });
    const code = rows.map((r) => r.letter).join('');
    const t = TYPES[code];
    const borderline = rows.filter((r) => Math.abs(r.pa - 50) < 8);

    return {
      headline: code,
      title: t.name,
      icon: t.icon,
      summary: t.tag,
      line: `${code} · ${t.name}`,
      viz: [{ type: 'bipolar', rows: rows.map((r) => ({ left: r.la, right: r.lb, value: r.pa })) }],
      sections: [
        { title: '你的优势', list: t.strengths },
        { title: '成长建议', list: t.growth },
        {
          title: '维度解读',
          list: rows.map((r) => {
            const lean = r.pa >= 50 ? r.pa : 100 - r.pa;
            const side = r.pa >= 50 ? r.la : r.lb;
            const desc = r.pa >= 50 ? r.da : r.db;
            return `${strengthWord(r.pa)}「${side}」（${lean}%）：${desc}。`;
          }),
        },
        ...(borderline.length
          ? [{ title: '边界提示', text: `你在 ${borderline.map((r) => r.la.slice(-1) + '/' + r.lb.slice(-1)).join('、')} 上几乎平衡，这意味着两种倾向你都能自如切换，类型字母在这里参考意义不大。` }]
          : []),
        { title: '理性看待', text: '类型代表"偏好"而非"能力"，每个人都会使用所有八种倾向。MBTI 类的二分法在学术界存在争议（例如重测时类型可能改变），如果想获得更科学的人格画像，推荐再做一次「大五人格测试」。' },
      ],
    };
  },
};
